const LangContext = createContext({ lang: "pt", setLang: () => {}, t: (k) => k });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem("mognus_lang");
    if (saved && DICTS[saved]) return saved;
    const nav = (navigator.language || "pt").slice(0, 2);
    return DICTS[nav] ? nav : "pt";
  });

  const setLang = (code) => {
    if (!DICTS[code]) return;
    setLangState(code);
    localStorage.setItem("mognus_lang", code);
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key) => (DICTS[lang] && DICTS[lang][key]) || pt[key] || key;

  return <LangContext.Provider value={{ lang, setLang, t, langs: LANGS }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
